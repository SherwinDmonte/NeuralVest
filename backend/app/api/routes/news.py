"""News endpoints: analysed articles stored by the Financial News Agent."""

from datetime import timedelta

from fastapi import APIRouter, Path, Query
from pymongo import DESCENDING

from app.database.database import get_database
from app.database.models import FINANCIAL_NEWS, SYMBOL_PATTERN
from app.database.repository import find_page
from app.utils.timing import utc_now
from app.utils.urls import safe_http_url

router = APIRouter(prefix="/api/news", tags=["news"])
SYMBOL = Path(pattern=SYMBOL_PATTERN, examples=["RELIANCE.NS"])
SENTIMENT_DISCLAIMER = ("Sentiment is judged by a small local AI model from headlines and short summaries. It can "
                        "be wrong and is not a prediction of future stock returns.")
SENTIMENTS = ("positive", "negative", "neutral", "uncertain")


def overall_from_counts(relevant: dict[str, int]) -> str:
    """The Financial News Agent's rule (agents/financial_news.overall_sentiment), applied to
    stored counts of relevant (high/medium relevance) articles."""
    if not sum(relevant.values()):
        return "insufficient_data"
    pos, neg = relevant.get("positive", 0), relevant.get("negative", 0)
    if pos == neg == 0:
        return "neutral"
    if pos == neg:
        return "mixed"
    return "positive" if pos > neg else "negative"


@router.get("/{symbol}/sentiment", summary="Sentiment breakdown of the stored news for a symbol")
def news_sentiment(symbol: str = SYMBOL, days: int = Query(14, ge=1, le=90,
                                                           description="Articles published in the last N days")) -> dict:
    since = utc_now() - timedelta(days=days)
    rows = list(get_database()[FINANCIAL_NEWS].aggregate([
        {"$match": {"symbol": symbol, "publication_date": {"$gte": since}}},
        {"$group": {"_id": {"sentiment": "$sentiment", "relevance": "$relevance"}, "n": {"$sum": 1},
                    "latest": {"$max": "$publication_date"}}},
    ]))
    breakdown = {s: 0 for s in SENTIMENTS}
    relevant = {s: 0 for s in SENTIMENTS}
    latest_dates = [r["latest"] for r in rows if r.get("latest")]
    for r in rows:
        sentiment, relevance = r["_id"].get("sentiment"), r["_id"].get("relevance")
        if sentiment not in breakdown:
            continue
        breakdown[sentiment] += r["n"]
        if relevance in ("high", "medium"):
            relevant[sentiment] += r["n"]
    total = sum(breakdown.values())
    return {
        "symbol": symbol, "lookback_days": days, "articles": total,
        "breakdown": breakdown,
        "breakdown_pct": {s: round(100 * n / total, 1) for s, n in breakdown.items()} if total else None,
        "relevant_breakdown": relevant,
        "overall_sentiment": overall_from_counts(relevant),
        "rule": "majority of positive vs negative among high/medium-relevance articles (same rule as the "
                "Financial News Agent)",
        "latest_article_at": max(latest_dates) if latest_dates else None,
        "note": None if total else "No stored articles in this period. Run an analysis to collect news.",
        "disclaimer": SENTIMENT_DISCLAIMER,
    }


@router.get("/{symbol}", summary="Stored, analysed news for a symbol (newest first, paginated)")
def stock_news(
    symbol: str = SYMBOL,
    sentiment: str | None = Query(None, pattern="^(positive|negative|neutral|uncertain)$"),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
) -> dict:
    query = {"symbol": symbol} | ({"sentiment": sentiment} if sentiment else {})
    result = find_page(get_database(), FINANCIAL_NEWS, query, sort=[("publication_date", DESCENDING)],
                       page=page, page_size=page_size)
    result["items"] = [{**a, "article_url": safe_http_url(a.get("article_url"))} for a in result["items"]]
    return {**result, "symbol": symbol,
            "disclaimer": "Summaries and sentiment are generated by a small local AI model and can be wrong. "
                          "Always read the original article."}
