"""News endpoints: analysed articles stored by the Financial News Agent."""

from fastapi import APIRouter, Path, Query
from pymongo import DESCENDING

from app.database.database import get_database
from app.database.models import FINANCIAL_NEWS, SYMBOL_PATTERN
from app.database.repository import find_page

router = APIRouter(prefix="/api/news", tags=["news"])


@router.get("/{symbol}", summary="Stored, analysed news for a symbol (newest first, paginated)")
def stock_news(
    symbol: str = Path(pattern=SYMBOL_PATTERN, examples=["RELIANCE.NS"]),
    sentiment: str | None = Query(None, pattern="^(positive|negative|neutral|uncertain)$"),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
) -> dict:
    query = {"symbol": symbol} | ({"sentiment": sentiment} if sentiment else {})
    result = find_page(get_database(), FINANCIAL_NEWS, query, sort=[("publication_date", DESCENDING)],
                       page=page, page_size=page_size)
    return {**result, "symbol": symbol,
            "disclaimer": "Summaries and sentiment are generated by a small local AI model and can be wrong. "
                          "Always read the original article."}
